function jpg(png, name) {
  const tmp = path.join(OUT, name.replace(/\.jpg$/, '.png'));
  fs.writeFileSync(tmp, png);
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', tmp, '-q:v', '2', path.join(OUT, name)]);
  fs.unlinkSync(tmp);
  return `${SET}/${name}`;
}

const items = [];
let n = 0;
const num = () => String(++n).padStart(2, '0');

// Карусел: корица, точки, призив.
function carousel(id, at, { eyebrow, title, sub, motif = null, points, cta, caption, tags }) {
  const total = points.length + 2;
  const slides = [
    { template: 'carouselCover', eyebrow, title, sub, motif },
    ...points.map(([t, text], i) => ({ template: 'carouselPoint', n: i + 1, title: t, text })),
    { template: 'carouselCta', title: cta, text: 'Изчислява се от датата, часа и мястото на раждане. Виж своята карта безплатно.', button: SITE, note: 'Линкът е в профила' },
  ].map((s, i) => ({ ...s, index: i + 1, total }));
  const p = num();
  const media = slides.map((s) => jpg(toPng(T[s.template]({ ...s, handle: HANDLE }), T.POST.w), `${p}-${id}-${s.index}.jpg`));
  items.push({ id: `${SET}-${p}-${id}`, at, type: 'carousel', media, caption: [...caption, [...BASE_TAGS, ...tags].join(' ')].join('\n\n') });
}

function story(st, at) {
  const p = num();
  items.push({ id: `${SET}-${p}-${st.id}`, at, type: 'story', media: [jpg(toPng(T[st.template](st), T.STORY.w), `${p}-${st.id}.jpg`)] });
}

function quiz(id, at, atAnswer, { eyebrow, title, options, answerTitle, answers }) {
  const letters = ['A', 'Б', 'В', 'Г', 'Д', 'Е'];
  story({ id, template: 'quizStory', eyebrow, title, options: options.map((text, i) => ({ letter: letters[i], text })), footer: 'Отговорът – довечера' }, at);
  story({ id: `${id}-answer`, template: 'quizStory', eyebrow: 'Отговорът', title: answerTitle, options: answers.map((text, i) => ({ letter: letters[i], text })), footer: `Провери точно: ${SITE}` }, atAnswer);
}

